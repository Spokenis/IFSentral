const { firefox } = require('playwright-core');
const B = 'https://127.0.0.1:38443'; const OUT = process.argv[2];
(async () => {
  const browser = await firefox.launch();
  const ctx = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1366, height: 800 } });
  const page = await ctx.newPage(); const erros = [];
  page.on('pageerror', e => erros.push(e.message.slice(0, 150)));
  page.on('console', m => { if (m.type() === 'error' && !/401/.test(m.text())) erros.push(m.text().slice(0, 150)); });
  const ok = (n, v) => console.log((v ? '[OK   ] ' : '[FALHA] ') + n);
  await page.goto(B + '/login'); 
  await page.fill('input[type="email"]', 'vitima@teste.dev'); await page.fill('input[type="password"]', 'Seg@2026xx');
  await Promise.all([page.waitForURL(/meus-projetos/, { timeout: 15000 }).catch(() => {}), page.click('button[type="submit"]')]);
  ok('login pelo formulário leva a /meus-projetos', page.url().includes('meus-projetos'));
  await page.waitForTimeout(1500);
  ok('lista de projetos mostra "Carga 01"', (await page.content()).includes('Carga 01'));
  await page.goto(B + '/projeto?id=30'); await page.waitForTimeout(3000);
  ok('página do projeto abre com as abas', await page.isVisible('#project-tabs'));
  const canvases = await page.$$eval('canvas', cs => cs.filter(c => c.width > 0 && c.height > 0).length);
  ok(`gráficos desenhados (canvas: ${canvases})`, canvases > 0);
  await page.click('#tab-sensores-tab'); await page.waitForTimeout(1000);
  ok('aba Dispositivos mostra os sensores', (await page.content()).includes('Sensor 01-01'));
  await page.screenshot({ path: OUT + '/firefox_projeto.png' });
  await page.goto(B + '/documentacao'); await page.waitForTimeout(1500);
  ok('documentação abre', (await page.title()).length > 0 && (await page.content()).includes('MQTT'));
  await page.goto(B + '/novo-grafico?project_id=30'); await page.waitForTimeout(1500);
  ok('tela de novo gráfico abre', await page.isVisible('#btn-salvar-grafico'));
  ok('sem erros de JavaScript', erros.length === 0); if (erros.length) console.log(erros);
  await browser.close();
})();
